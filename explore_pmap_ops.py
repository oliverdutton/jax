# Test 4: Regular function (no pmap)
print("\n" + "="*80)
print("TEST 4: Regular function (no pmap)")
print("="*80)

def f_regular(x):
    return jnp.sum(x) * x

x = jnp.array([1.0, 2.0, 3.0])
lowered = jax.jit(f_regular).lower(x)
mlir_module = lowered.compiler_ir(dialect='stablehlo')
print(mlir_module)
