#!/usr/bin/env python3
"""
Explore what StableHLO operations are generated by pmap, shard_map, and collective ops.
"""

import jax
import jax.numpy as jnp
from jax import lax
import numpy as np


# Test 1: Simple pmap
print("="*80)
print("TEST 1: Simple pmap")
print("="*80)

def f_pmap(x):
    return x * 2.0

x = jnp.array([[1.0, 2.0], [3.0, 4.0]])
f_pmapped = jax.pmap(f_pmap)

try:
    lowered = f_pmapped.lower(x)
    mlir_module = lowered.compiler_ir(dialect='stablehlo')
    print(mlir_module)
except Exception as e:
    print(f"Error: {e}")


# Test 2: pmap with psum
print("\n" + "="*80)
print("TEST 2: pmap with lax.psum")
